import { CanvasDocument, CanvasTheme } from '../types/strawpage';

export function createStarterDocument(theme: CanvasTheme = 'choco'): CanvasDocument {
  const doc = buildRawStarterDocument(theme);
  return {
    ...doc,
    canvasHeight: 1120,
    items: doc.items.map((item) => ({ ...item, x: item.x + 30 })),
  };
}

